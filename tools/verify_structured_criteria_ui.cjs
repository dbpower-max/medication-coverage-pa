const fs=require('fs'),vm=require('vm');
const assert=(ok,msg)=>{if(!ok)throw Error(msg)};
const src=fs.readFileSync('_site/app.js','utf8');
const start=src.indexOf('  function structuredPolicyPanel('),end=src.indexOf('  // Slice, never summarize:',start);
assert(start>0&&end>start,'Structured clinical criteria renderer missing');
const ctx={escapeHtml:s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))};
vm.createContext(ctx);vm.runInContext(src.slice(start,end),ctx);
ctx.policy={id:'ref',planId:'ahcccs-ffs-aihp',structuredCriteriaUrl:'./clinical-criteria/gl-99673.json?v=abc',structuredBranchCount:8};
assert(vm.runInContext('structuredPolicyPanel(policy)',ctx).includes('data-read-criteria="ref"'),'Source panel not connected');
ctx.policy.planId='uhc-community-az';
assert(vm.runInContext('structuredPolicyPanel(policy)',ctx)==='','Statewide clinical criteria promoted to selected-plan criteria');
ctx.policy=JSON.parse(fs.readFileSync('_site/clinical-criteria/gl-99673.json','utf8'));
let html=vm.runInContext('structuredCriteriaMarkup(policy)',ctx);
assert(html.includes('Clinical criteria — source order and logic:')&&html.includes('Initial Authorization')&&html.includes('Reauthorization'),'Clinical stages missing');
assert(html.includes('Approval duration')&&html.includes('Clinician approval pending'),'Renderer changed review status');
ctx.policy.branches[0].criteria[0].text='<script>alert(1)</script>';
html=vm.runInContext('structuredCriteriaMarkup(policy)',ctx);
assert(html.includes('&lt;script&gt;')&&!html.includes('<script>'),'Source text rendered as active HTML');
assert(src.includes('structured.policyCode !== policy.policyCode')&&src.includes('structured.sourceEffective !== policy.sourceEffective'),'Reader fails to verify source identity');
assert(src.includes('content.hidden = !content.hidden')&&src.includes('Retry clinical criteria'),'Toggle or retry missing');
console.log('PASS: structured clinical panels, scope isolation, initial/renewal branches, source escaping and source identity guards');

ctx.policy=JSON.parse(fs.readFileSync('_site/clinical-criteria/gl-509188.json','utf8'));
ctx.pdf={sourceUrl:'./sources/policy.pdf',sourcePage:2013,sourceLastPage:2019};
html=vm.runInContext('structuredCriteriaMarkup(policy,pdf)',ctx);
assert(html.includes('policy.pdf#page=2018'), 'Later-page product criteria lost their PDF position');
